//! Fetches the OCR weights at build time and embeds them.
//!
//! The alternative — downloading on first use — would leave the tool unable to
//! read a scan until it had been online at least once, and would put several
//! megabytes somewhere the user has to take on trust. Embedding costs about
//! 6.9 MB and makes "works with no setup" true in the strong sense: offline
//! from the moment it is installed.
//!
//! The pattern mirrors what `pdfium-bundled` does for the PDF engine: fetch
//! once into a cache shared across builds, verify the digest, and copy into
//! `OUT_DIR` for `include_bytes!`.

use std::path::{Path, PathBuf};
use std::process::Command;

use sha2::{Digest, Sha256};

/// Filename, URL, SHA-256.
///
/// These digests are the ones `rapidocr-core` pins for the model set it calls
/// `ppocrv6-tiny`. A test compares the two lists, so an upstream update fails
/// loudly here instead of silently embedding weights the crate no longer
/// expects to find.
const MODELS: &[(&str, &str, &str)] = &[
    (
        "PP-OCRv6_det_tiny.onnx",
        "https://www.modelscope.cn/models/RapidAI/RapidOCR/resolve/v3.9.0/onnx/PP-OCRv6/det/PP-OCRv6_det_tiny.onnx",
        "f42c0fbd294d95eac1a550e131b277dac97462c8025fa4b6c3cec1b7894bd3d5",
    ),
    (
        "PP-OCRv6_rec_tiny.onnx",
        "https://www.modelscope.cn/models/RapidAI/RapidOCR/resolve/v3.9.0/onnx/PP-OCRv6/rec/PP-OCRv6_rec_tiny.onnx",
        "e16e242de5937ad92609223f19bc2aff3727ee40b095f996907c24749bad251b",
    ),
    // Shared across model sets, and required: the pipeline classifies text
    // direction before recognising it.
    (
        "ch_ppocr_mobile_v2.0_cls_mobile.onnx",
        "https://www.modelscope.cn/models/RapidAI/RapidOCR/resolve/v3.9.0/onnx/PP-OCRv4/cls/ch_ppocr_mobile_v2.0_cls_mobile.onnx",
        "e47acedf663230f8863ff1ab0e64dd2d82b838fceb5957146dab185a89d6215c",
    ),
    (
        "ppocrv6_tiny_dict.txt",
        "https://www.modelscope.cn/models/RapidAI/RapidOCR/resolve/master/paddle/PP-OCRv6/rec/PP-OCRv6_rec_tiny/ppocrv6_tiny_dict.txt",
        "c5cbe34ef40c29c4df07ed012bf96569cb69a2d2a01a07027e9f13cb832bd9cd",
    ),
];

fn main() {
    println!("cargo:rerun-if-changed=build.rs");

    let out_dir = PathBuf::from(std::env::var("OUT_DIR").expect("OUT_DIR"));
    let models_dir = out_dir.join("ocr-models");
    std::fs::create_dir_all(&models_dir).expect("create the model directory");

    let mut pins = String::from("// Generated by build.rs. Do not edit.\n");
    pins.push_str("pub const PINS: &[(&str, &str)] = &[\n");

    for (filename, url, expected) in MODELS {
        let cached = cached_path(filename);
        if !cached.is_file() || !digest_matches(&cached, expected) {
            download(url, &cached);
        }

        // Checked after every download, and after a cache hit too: a corrupted
        // cache is the failure that would otherwise be found by the model
        // producing nonsense at run time.
        if !digest_matches(&cached, expected) {
            panic!(
                "the digest of {filename} does not match the one pinned here.\n\
                 Do not work around this: confirm which build upstream published before\n\
                 changing the pin, because the weights are what the recogniser reads."
            );
        }

        std::fs::copy(&cached, models_dir.join(filename)).expect("copy into OUT_DIR");
        pins.push_str(&format!("    (\"{filename}\", \"{expected}\"),\n"));
    }

    pins.push_str("];\n");
    std::fs::write(out_dir.join("model_pins.rs"), pins).expect("write the generated pins");
}

/// A cache shared between builds, so a clean rebuild does not re-download.
fn cached_path(filename: &str) -> PathBuf {
    let root = std::env::var("DOCFUSION_MODEL_CACHE")
        .map(PathBuf::from)
        .unwrap_or_else(|_| {
            std::env::var("CARGO_HOME")
                .map(PathBuf::from)
                .or_else(|_| std::env::var("USERPROFILE").map(PathBuf::from))
                .unwrap_or_else(|_| std::env::temp_dir())
                .join("docfusion-models")
        });

    root.join(filename)
}

fn digest_matches(path: &Path, expected: &str) -> bool {
    let Ok(bytes) = std::fs::read(path) else {
        return false;
    };

    let actual: String = Sha256::digest(&bytes)
        .iter()
        .map(|byte| format!("{byte:02x}"))
        .collect();

    actual == expected
}

/// Downloads with whatever the machine already has.
///
/// `curl` first because it is present on Windows 10 and later and on every Unix
/// worth naming; PowerShell is the fallback rather than the first choice
/// because invoking it costs a noticeable fraction of a second per file.
fn download(url: &str, destination: &Path) {
    if let Some(parent) = destination.parent() {
        std::fs::create_dir_all(parent).expect("create the cache directory");
    }

    println!("cargo:warning=docfusion: downloading {}", destination.display());

    let via_curl = Command::new("curl")
        .args(["-L", "-f", "-s", "--retry", "3", "-o"])
        .arg(destination)
        .arg(url)
        .status();

    if matches!(via_curl, Ok(status) if status.success()) {
        return;
    }

    let via_powershell = Command::new("powershell")
        .args([
            "-NoProfile",
            "-NonInteractive",
            "-Command",
            &format!(
                "Invoke-WebRequest -Uri '{url}' -OutFile '{}' -UseBasicParsing",
                destination.display()
            ),
        ])
        .status();

    if matches!(via_powershell, Ok(status) if status.success()) {
        return;
    }

    panic!(
        "\ncould not download {url}\n\
         Both curl and PowerShell failed. Download it by hand into\n  {}\n\
         and run the build again.",
        destination.display()
    );
}
